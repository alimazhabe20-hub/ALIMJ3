def _looks_truncated(answer: str) -> bool:
    """تشخیص پاسخ واقعاً ناتمام؛ برای جلوگیری از ارسال جواب بریده‌شده."""
    a = (answer or "").strip()
    if not a:
        return False

    # نشانه‌های خیلی قویِ قطع شدن خروجی
    if a.endswith(("...", "…", ":", "—", "-", ",", ";", "/")):
        return True

    # پاسخ‌هایی که با کلمه/عبارت وابسته تمام شده‌اند معمولاً وسط جمله قطع شده‌اند.
    tail = a.split()[-1].strip("،؛,:.!؟?()[]{}\"'`*_-").lower()
    dangling_words = {
        "اگر", "که", "و", "یا", "اما", "ولی", "برای", "با", "در", "از",
        "به", "تا", "را", "این", "آن", "یک", "هم", "نیز", "همچنین",
        "معمولاً", "احتمالاً", "بنابراین", "زیرا", "چون", "پس", "البته",
        "درصورتیکه", "درصورتی", "اگرچه", "هرچند", "مثلاً", "مثل",
    }
    if len(a) >= 500 and tail in dangling_words:
        return True

    # اگر متن نسبتاً بلند است ولی با پایان جمله تمام نشده، احتمال قطع بالا است.
    if len(a) >= 1400 and not __import__("re").search(r"[.!?؟۔]\s*$", a):
        return True

    # خروجی خیلی بلند تقریباً همیشه نیاز به ادامه/تقسیم امن دارد.
    return len(a) >= 3200

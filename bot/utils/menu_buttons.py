def _norm(text: str) -> str:
    t = _ZW.sub("", (text or "").strip())
    t = re.sub(r"\s+", " ", t)
    return t


def _core(text: str) -> str:
    t = _norm(text)
    t = _EMOJI.sub("", t)
    t = t.replace("\u200c", "").replace(" ", "").strip()
    return t



def is_reply_menu_button(text: str) -> bool:
    """True اگر متن همان دکمه منو باشد (نه ورودی کاربر)."""
    t = _norm(text)
    if not t:
        return False
    if t in _FULL_LABELS:
        return True
    compact = t.replace(" ", "")
    if any(compact == x.replace(" ", "") for x in _FULL_LABELS):
        return True
    c = _core(t)
    if c and c in _CORE_LABELS:
        return True
    if len(t) <= 48 and t.startswith(_PREFIXES):
        # ورودی تاریخ/عدد خالص را منو حساب نکن
        if re.match(r"^[0-9۰-۹/\-\s.]+$", t):
            return False
        return True
    return False


def match_date_menu_state(text: str) -> str | None:
    c = _core(text)
    if not c:
        return None
    for k, state in _DATE_STATE.items():
        kk = k.replace(" ", "").replace("\u200c", "")
        if c == kk or c.endswith(kk):
            return state
    return None



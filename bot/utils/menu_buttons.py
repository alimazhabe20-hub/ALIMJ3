def _norm(text: str) -> str:
    t = _ZW.sub("", (text or "").strip())
    t = re.sub(r"\s+", " ", t)
    return t


def _core(text: str) -> str:
    """متن بدون ایموجی و بدون نیم‌فاصله."""
    t = _norm(text)
    # حذف نمادهای رایج ایموجی/پیکتوگراف
    t = re.sub(r"[\U0001F300-\U0010FFFF]", "", t)
    t = re.sub(r"[\u2600-\u27BF]", "", t)
    t = t.strip()
    t = t.replace("‌", "").replace(" ", "")
    return t


def is_reply_menu_button(text: str) -> bool:
    t = _norm(text)
    if not t:
        return False
    if t in FULL_LABELS:
        return True
    # بدون فاصلهٔ اضافی
    if t.replace(" ", "") in {x.replace(" ", "") for x in FULL_LABELS}:
        return True
    if t.startswith(_PREFIXES):
        # اگر فقط عدد/تاریخ باشد نه
        core = _core(t)
        if core and any(k.replace(" ", "").replace("‌", "") in core or core in k.replace(" ", "").replace("‌", "") for k in DATE_CORE_TO_STATE):
            return True
        # پیشوند منوی عمومی
        if any(t.startswith(p) for p in ("➕", "🏠", "🔙", "💰", "🕌", "🛠", "🎮", "🎨", "👤", "📥", "🤖")):
            return True
        # پیشوند تاریخ
        if any(t.startswith(p) for p in ("🔄", "🎂", "🎉", "♈", "🌙", "📆", "👥", "📅", "🔍", "🌸", "🌍", "⏳")):
            return True
    core = _core(t)
    for k in DATE_CORE_TO_STATE:
        kk = k.replace(" ", "").replace("‌", "")
        if core == kk or core.endswith(kk):
            return True
    return False


def match_date_menu_state(text: str) -> str | None:
    """اگر دکمهٔ تاریخ/سن بود، نام waiting_for مربوط را برگردان."""
    t = _norm(text)
    core = _core(t)

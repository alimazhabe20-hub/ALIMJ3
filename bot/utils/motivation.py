async def get_motivation_async(user_id: int | None = None) -> str:
    """اول API کتاب/جهانی، وگرنه مخزن کتاب محلی."""
    # گاهی مستقیم از کتاب محلی (قوی و فارسی)
    if BOOK_QUOTES and random.random() < 0.35:
        return get_motivation_rich(user_id)

    eng = author = book = kind = None
    fa = None
    try:
        async with httpx.AsyncClient(timeout=20.0, follow_redirects=True) as client:
            await _refresh_pool(client)
            recent = set(_RECENT.get(int(user_id), [])) if user_id is not None else set()
            # اولویت نقل‌قول‌هایی که اسم کتاب دارند
            bookish = [x for x in _API_POOL if x[3] == "کتاب" and x[0] not in recent]
            others = [x for x in _API_POOL if x[0] not in recent]
            pool = bookish or others or list(_API_POOL)
            if pool:
                eng, author, book, kind = random.choice(pool)
                if not re.search(r"[\u0600-\u06FF]", eng):
                    fa = await _en_to_fa(eng, client)
    except Exception as e:
        logger.error("motivation api: %s", e)

    if eng:
        body = fa if fa else eng
        _remember(user_id, body, eng)
        cat = _category_for_now()
        emoji = _CAT_EMOJI.get(cat, "💖")
        src_label = "کتاب (API)" if kind == "کتاب" else (book or "API")
        lines = [
            "💖 **جمله انگیزشی**",
            f"{emoji} حال‌وهوا: **{cat}**",
            f"📖 منبع: {src_label} · مخزن {len(_API_POOL) + len(BOOK_QUOTES)}+",
            "",
            f"«{body}»",
            f"— **{author or 'ناشناس'}**",
        ]
        if book and kind == "کتاب":
            lines.append(f"📚 {book}")
        elif book and kind == "API" and book not in ("ZenQuotes",) and not book.startswith("Quotable"):
            lines.append(f"📚 {book}")
        if not fa and not re.search(r"[\u0600-\u06FF]", body):
            lines.append("")
            lines.append("_(ترجمه موقت در دسترس نبود)_")
        lines.append("")
        lines.append("💡 دوباره بزن — از کتاب‌ها و منابع جهانی می‌آید.")
        return "\n".join(lines)

    return get_motivation_rich(user_id)

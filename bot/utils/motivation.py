    if messages is not None:
        pool = list(messages)
        if not pool:
            return ""
        index = random.randint(0, len(pool) - 1)
        if len(pool) > 1:
            while index == last_index:
                index = random.randint(0, len(pool) - 1)
        last_index = index
        return pool[index]
    # ترجیح کتاب محلی
    if BOOK_QUOTES and random.random() < 0.7:
        t, a, b = _pick_book_local(user_id)
        return f"«{t}»\n— {a} · 📖 {b}"
    _, c = _pick_local_cat(user_id)
    return c



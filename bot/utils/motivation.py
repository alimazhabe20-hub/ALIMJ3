def _category_for_now() -> str:
    try:
        hour = datetime.now().hour
    except Exception:
        return random.choice(list(MOTIVATION_BY_CAT.keys()))
    if 5 <= hour < 11:
        return random.choice(["رشد", "تلاش", "امید", "درخشش"])
    if 11 <= hour < 17:
        return random.choice(["تلاش", "درخشش", "رشد", "امید"])
    if 17 <= hour < 21:
        return random.choice(["امید", "درخشش", "آرامش", "رشد"])
    return random.choice(["آرامش", "امید", "رشد"])


def _clean(s: str) -> str:
    s = re.sub(r"<[^>]+>", " ", s or "")
    s = re.sub(r"\s+", " ", s).strip()
    s = s.strip("“”\"'")
    return s


def _quality_ok(q: str) -> bool:
    q = _clean(q)
    if len(q) < 12 or len(q) > 320:
        return False
    if _BAD_EN.search(q):
        return False
    if q.count(" ") < 2:
        return False
    return True


def _remember(user_id: int | None, *texts: str) -> None:
    if user_id is None:
        return
    uid = int(user_id)
    lst = _RECENT[uid]
    for t in texts:
        if t:
            lst.append(t)
    if len(lst) > _RECENT_MAX:
        _RECENT[uid] = lst[-_RECENT_MAX:]


async def _en_to_fa(text: str, client: httpx.AsyncClient) -> Optional[str]:
    text = _clean(text)
    if len(text) < 3:
        return None
    chunk = text[:380]
    headers = {"User-Agent": "ALIMJ3/1.0", "Accept": "application/json,text/plain,*/*"}

    def _ok(tr: str) -> bool:
        if not tr or tr.lower() == chunk.lower():
            return False
        u = tr.upper()
        if any(x in u for x in ("INVALID", "MYMEMORY WARNING", "USED ALL AVAILABLE")):
            return False
        return len(re.findall(r"[\u0600-\u06FF]", tr)) >= 6

    try:
        r = await client.get(
            "https://translate.googleapis.com/translate_a/single",
            params={"client": "gtx", "sl": "en", "tl": "fa", "dt": "t", "q": chunk},
            headers=headers, timeout=8.0,
        )
        if r.status_code == 200 and r.content:
            data = r.json()
            parts = []
            if isinstance(data, list) and data and isinstance(data[0], list):
                for row in data[0]:
                    if row and row[0]:
                        parts.append(str(row[0]))
            tr = _clean("".join(parts))
            if _ok(tr):
                return tr
    except Exception as e:
        logger.debug("gtx: %s", e)
    try:
        r = await client.get(
            "https://api.mymemory.translated.net/get",
            params={"q": chunk, "langpair": "en|fa"},
            headers=headers, timeout=8.0,
        )
        if r.status_code == 200:
            tr = _clean(((r.json().get("responseData") or {}).get("translatedText") or ""))
            if _ok(tr):
                return tr
    except Exception as e:
        logger.debug("mymemory: %s", e)
    return None


async def _fetch_book_api(client: httpx.AsyncClient) -> list[tuple[str, str, str, str]]:
    """api.hamatim.com — quote + book title."""
    out = []
    for _ in range(8):
        try:
            r = await client.get(
                "https://api.hamatim.com/quote",
                headers={"User-Agent": "ALIMJ3/1.0", "Accept": "application/json"},
                timeout=10.0,
            )
            if r.status_code != 200:
                continue
            d = r.json()
            if not isinstance(d, dict):
                continue
            q = _clean(str(d.get("text") or ""))
            a = _clean(str(d.get("author") or ""))
            b = _clean(str(d.get("book") or ""))
            if _quality_ok(q):
                out.append((q, a or "ناشناس", b or "کتاب", "کتاب"))
        except Exception as e:
            logger.debug("hamatim: %s", e)
            break
    return out


async def _fetch_zen_quotable(client: httpx.AsyncClient) -> list[tuple[str, str, str, str]]:
    out = []
    try:
        r = await client.get("https://zenquotes.io/api/quotes", headers={"User-Agent": "ALIMJ3/1.0"}, timeout=12.0)
        if r.status_code == 200:
            for item in r.json() if isinstance(r.json(), list) else []:
                if isinstance(item, dict):
                    q, a = _clean(str(item.get("q") or "")), _clean(str(item.get("a") or ""))
                    if _quality_ok(q):
                        out.append((q, a or "ناشناس", "ZenQuotes", "API"))
    except Exception as e:
        logger.debug("zen: %s", e)
    for tags in ("inspirational", "success", "wisdom", "literature"):
        try:
            r = await client.get(
                "https://api.quotable.io/quotes",
                params={"tags": tags, "limit": 15},
                headers={"User-Agent": "ALIMJ3/1.0"},
                timeout=10.0,
            )
            if r.status_code == 200:
                results = (r.json() or {}).get("results") if isinstance(r.json(), dict) else []
                for item in results or []:
                    if isinstance(item, dict):
                        q = _clean(str(item.get("content") or ""))
                        a = _clean(str(item.get("author") or ""))
                        if _quality_ok(q):
                            out.append((q, a or "ناشناس", f"Quotable/{tags}", "API"))
        except Exception as e:
            logger.debug("quotable: %s", e)
    return out


async def _refresh_pool(client: httpx.AsyncClient) -> None:
    global _API_POOL, _API_POOL_TS
    now = time.time()
    if _API_POOL and (now - _API_POOL_TS) < _API_POOL_TTL:
        return
    pool = []
    pool.extend(await _fetch_book_api(client))
    pool.extend(await _fetch_zen_quotable(client))
    seen = set()
    uniq = []
    for t, a, b, k in pool:
        key = t.lower()[:90]
        if key in seen:
            continue
        seen.add(key)
        uniq.append((t, a, b, k))
    if uniq:
        _API_POOL = uniq
        _API_POOL_TS = now
        logger.debug("motivation pool=%s", len(uniq))


def _pick_book_local(user_id: int | None) -> tuple[str, str, str]:
    recent = set(_RECENT.get(int(user_id), [])) if user_id is not None else set()
    options = [x for x in BOOK_QUOTES if x[0] not in recent]
    if not options:
        options = list(BOOK_QUOTES)
    text, author, book = random.choice(options)
    _remember(user_id, text)
    return text, author, book


def _pick_local_cat(user_id: int | None) -> tuple[str, str]:
    cat = _category_for_now()
    options = list(MOTIVATION_BY_CAT.get(cat) or motivation_messages)
    if user_id is not None:
        recent = _RECENT.get(int(user_id), [])
        filtered = [q for q in options if q not in recent]
        if filtered:
            options = filtered
    choice = random.choice(options or motivation_messages)
    _remember(user_id, choice)
    return cat, choice



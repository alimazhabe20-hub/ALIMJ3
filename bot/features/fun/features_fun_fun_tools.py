async def _translate_en_to_fa(text: str, client: httpx.AsyncClient) -> str | None:
    """ترجمه کوتاه انگلیسی → فارسی (چند سرویس رایگان)."""
    text = (text or "").strip()
    if len(text) < 3:
        return None
    chunk = text[:450]

    def _ok(tr: str) -> bool:
        if not tr or tr.lower() == chunk.lower():
            return False
        u = tr.upper()
        if any(x in u for x in ("INVALID", "QUERY LENGTH", "MYMEMORY WARNING", "USED ALL AVAILABLE")):
            return False
        # باید حداقل کمی فارسی داشته باشد
        if not re.search(r"[آ-ی]", tr):
            return False
        return True

    # ۱) Google Translate endpoint عمومی (بدون کلید)
    try:
        r = await client.get(
            "https://translate.googleapis.com/translate_a/single",
            params={"client": "gtx", "sl": "en", "tl": "fa", "dt": "t", "q": chunk},
            timeout=6.0,
        )
        if r.status_code == 200:
            data = r.json()
            parts = []
            if isinstance(data, list) and data and isinstance(data[0], list):
                for row in data[0]:
                    if row and row[0]:
                        parts.append(str(row[0]))
            tr = "".join(parts).strip()
            if _ok(tr):
                return tr
    except Exception as e:
        logger.debug("fact gtx: %s", e)

    # ۲) MyMemory
    try:
        r = await client.get(
            "https://api.mymemory.translated.net/get",
            params={"q": chunk, "langpair": "en|fa"},
            timeout=6.0,
        )
        if r.status_code == 200:
            tr = ((r.json().get("responseData") or {}).get("translatedText") or "").strip()
            if _ok(tr):
                return tr
    except Exception as e:
        logger.debug("fact mymemory: %s", e)

    return None



_FACT_RECENT = defaultdict(list)
_FACT_RECENT_MAX = 50


async def _fetch_useless_fact(client: httpx.AsyncClient):
    try:
        r = await client.get(
            "https://uselessfacts.jsph.pl/api/v2/facts/random",
            params={"language": "en"},
            headers={"Accept": "application/json"},
            timeout=8.0,
        )
        if r.status_code != 200:
            return None
        data = r.json()
        text = (data.get("text") or data.get("fact") or "").strip()
        return text or None
    except Exception as e:
        logger.debug("uselessfacts: %s", e)
        return None


async def _fetch_numbers_fact(client: httpx.AsyncClient):
    try:
        r = await client.get(
            "http://numbersapi.com/random/trivia",
            timeout=6.0,
        )
        if r.status_code != 200:
            return None
        t = (r.text or "").strip()
        return t if len(t) > 20 else None
    except Exception as e:
        logger.debug("numbersapi: %s", e)
        return None


def _pick_local_fact(user_id=None):
    recent = _FACT_RECENT.get(int(user_id), []) if user_id is not None else []
    options = [f for f in FACTS if f not in recent]
    if not options:
        options = list(FACTS)
    choice = random.choice(options)
    if user_id is not None:
        uid = int(user_id)
        lst = _FACT_RECENT[uid]
        lst.append(choice)
        if len(lst) > _FACT_RECENT_MAX:
            _FACT_RECENT[uid] = lst[-_FACT_RECENT_MAX:]
    return choice


async def fact_of_day(user_id=None):
    """دانستنی با API + ترجمه؛ در غیر این صورت محلی گسترده و ضدتکرار."""
    fact_fa = None
    try:
        async with httpx.AsyncClient(timeout=14.0, follow_redirects=True) as client:
            eng = await _fetch_useless_fact(client)
            if not eng:
                eng = await _fetch_numbers_fact(client)
            if eng:
                fact_fa = await _translate_en_to_fa(eng, client)
    except Exception as e:
        logger.error("fact_of_day api: %s", e)

    if fact_fa and len(re.findall(r"[\u0600-\u06FF]", fact_fa)) >= 10:
        if user_id is not None:
            uid = int(user_id)
            lst = _FACT_RECENT[uid]
            lst.append(fact_fa)
            if len(lst) > _FACT_RECENT_MAX:
                _FACT_RECENT[uid] = lst[-_FACT_RECENT_MAX:]
        return f"🧠 **دانستنی**\n\n{fact_fa}"

    fact_fa = _pick_local_fact(user_id)
    return f"🧠 **دانستنی**\n\n{fact_fa}"




